from typing import Dict, List, Any


class RemediationEngine:
    """
    Generates actionable, cloud-native hardening configurations (Model Armor,
    AWS Bedrock Guardrails, Azure Content Safety, and Terraform Organization Policies)
    for identified gaps and vulnerabilities.
    """

    @staticmethod
    def generate_remediations(failed_control_ids: List[str]) -> Dict[str, Any]:
        """
        Synthesizes remediation payloads for specific control failures.
        """
        remediations = {}

        # 1. Google Cloud Model Armor Remediation
        if any("GCP" in cid or "ARM" in cid or "APP-02" in cid for cid in failed_control_ids):
            remediations["google_cloud_model_armor"] = {
                "template_name": "aispr-model-armor-hardened-floor",
                "version": "2.0.0",
                "filters": {
                    "prompt_injection_strength": "HIGH",
                    "jailbreak_protection": "BLOCK_ALL",
                    "system_prompt_extraction": "BLOCK_ALL",
                    "pii_redaction": {
                        "enabled": True,
                        "dlp_deidentify_template": "projects/PROJECT_ID/locations/global/deidentifyTemplates/AI_SPR_PII_REDACT_ID"
                    }
                }
            }

        # 2. AWS Bedrock Guardrail Remediation
        if any("AWS" in cid or "BED" in cid for cid in failed_control_ids):
            remediations["aws_bedrock_guardrail"] = {
                "name": "aispr-bedrock-guardrail-prod",
                "description": "Generated by AISPR Agentic Platform for prompt injection and PII mitigation",
                "contentPolicyConfig": {
                    "filtersConfig": [
                        {"type": "PROMPT_ATTACK", "inputStrength": "HIGH", "outputStrength": "NONE"},
                        {"type": "MISCONDUCT", "inputStrength": "HIGH", "outputStrength": "HIGH"}
                    ]
                },
                "sensitiveInformationPolicyConfig": {
                    "piiEntitiesConfig": [
                        {"type": "CREDIT_DEBIT_CARD_NUMBER", "action": "BLOCK"},
                        {"type": "US_SOCIAL_SECURITY_NUMBER", "action": "BLOCK"},
                        {"type": "EMAIL", "action": "ANONYMIZE"}
                    ]
                }
            }

        # 3. Azure AI Content Safety Remediation
        if any("AZ" in cid or "AZURE" in cid for cid in failed_control_ids):
            remediations["azure_ai_content_safety"] = {
                "blocklist_name": "aispr-azure-prompt-shield",
                "categories": [
                    {"category": "Hate", "blocking_threshold": "Medium"},
                    {"category": "Violence", "blocking_threshold": "Medium"},
                    {"category": "PromptShield_UserInjection", "enabled": True},
                    {"category": "PromptShield_DocumentInjection", "enabled": True}
                ]
            }

        # 4. Terraform Organization Policy Hardening
        if any("SHADOW" in cid or "VULN" in cid or "INF" in cid for cid in failed_control_ids):
            remediations["terraform_hardening_blueprint"] = """
# AISPR Automated Hardening: Restrict Unmanaged AI Workbenches & Enforce CMEK
resource "google_org_policy_policy" "restrict_vertex_workbench" {
  name   = "projects/${var.project_id}/policies/vertexai.restrictWorkbenchCreation"
  parent = "projects/${var.project_id}"
  spec {
    rules {
      enforce = "TRUE"
    }
  }
}

resource "google_org_policy_policy" "require_cmek" {
  name   = "projects/${var.project_id}/policies/gcp.restrictNonCmekServices"
  parent = "projects/${var.project_id}"
  spec {
    rules {
      values {
        allowed_values = ["is:projects/${var.project_id}/locations/us-central1/keyRings/aispr-keyring"]
      }
    }
  }
}
"""

        return remediations

